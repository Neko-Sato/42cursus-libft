#include <ft_put_fd.h>

void	ft_putbin_fd(int n, int fd)
{
	int		i;
	char	s[33];

	i = 0;
	while (i < 32)
	{
		s[i] = '0' + (n >> (32 - i));
		i++;
	}
	s[i] = '\0';
	ft_putstr_fd(s, fd);
}
